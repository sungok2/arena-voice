const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const script=fs.readFileSync(path.join(__dirname,'../app/src/main/assets/module_draft.js'),'utf8');
const w={};vm.runInNewContext(script,{window:w},{filename:'module_draft.js'});
const d=w.ACADEMY_MODULE_DRAFTS;
assert.equal(d.getReflection('DF-001:1','saved'),'saved');
assert.equal(JSON.stringify(d.getLab('DF-001:1',{a:'5'})),JSON.stringify({a:'5'}));
d.capture('DF-001:1','입력 중인 학습 메모',{count:'15',choice:'B'});
assert.equal(d.getReflection('DF-001:1','saved'),'입력 중인 학습 메모');
assert.equal(d.getLab('DF-001:1',{count:'1'}).count,'15');
assert.equal(d.getLab('DF-001:1',{}).choice,'B');
assert.equal(d.getReflection('DF-001:2','other'),'other');
d.capture('DF-001:1','x'.repeat(4000),{count:'1'.repeat(100)});
assert.equal(d.getReflection('DF-001:1','').length,3000);
assert.equal(d.getLab('DF-001:1',{}).count.length,80);
d.clear('DF-001:1');
assert.equal(d.getReflection('DF-001:1','saved'),'saved');
assert.equal(d.getLab('DF-001:1',{count:'5'}).count,'5');
const app=fs.readFileSync(path.join(__dirname,'../app/src/main/assets/app.js'),'utf8');
const html=fs.readFileSync(path.join(__dirname,'../app/src/main/assets/index.html'),'utf8');
assert(html.indexOf('<script src="module_draft.js"></script>')>=0);
assert(html.indexOf('module_draft.js')<html.indexOf('<script src="app.js"></script>'));
assert(app.includes('function captureModuleFields()'));
assert(app.includes('getReflection(key,e.reflection'));
assert(app.includes('getLab(moduleKey(),e.labDraft'));
assert(app.includes("if(act==='module-choice'){captureModuleFields();"));
assert(app.includes("if(failed.length){captureModuleFields();"));
assert(app.includes("if(act==='back-to-course'){captureModuleFields();"));
assert(app.includes("if(openedModule!==null){captureModuleFields();"));
assert(app.includes('ACADEMY_MODULE_DRAFTS.clear(key)'));
console.log('MODULE_DRAFT_QA_PASS: saved fallback, unsaved reflection, lab values, module isolation, bounds, cleanup, integration hooks');
